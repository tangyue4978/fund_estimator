create or replace function private.current_app_user_id()
returns text
language sql
stable
security definer
set search_path = pg_catalog
as $$
    select u.user_id
    from public.app_users as u
    where u.auth_user_id = (select auth.uid())
    limit 1
$$;

revoke all on function private.current_app_user_id() from public;
grant execute on function private.current_app_user_id() to authenticated, service_role;

alter table public.app_users enable row level security;
alter table public.app_watchlist enable row level security;
alter table public.app_adjustments enable row level security;
alter table public.app_daily_ledger enable row level security;

