-- Fund Estimator security hardening
-- Apply through the Supabase migration workflow after taking a backup and
-- running the preflight queries documented in docs/SECURITY_DEPLOYMENT.md.
-- This file is intentionally never executed by the application.

begin;

create schema if not exists private;
revoke all on schema private from public;
grant usage on schema private to authenticated, service_role;

create table if not exists public.app_users (
    user_id text primary key,
    phone text not null unique,
    password_hash text not null,
    auth_user_id uuid,
    developer text,
    inviter text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

alter table public.app_users add column if not exists auth_user_id uuid;

create table if not exists public.app_watchlist (
    id bigint generated by default as identity primary key,
    user_id text not null,
    code text not null,
    created_at timestamptz not null default now()
);

create table if not exists public.app_adjustments (
    id text not null,
    user_id text not null,
    type text not null,
    code text not null,
    effective_date date not null,
    shares double precision not null default 0,
    price double precision not null default 0,
    cash double precision not null default 0,
    note text,
    source text not null default 'manual',
    created_at timestamptz not null default now()
);

alter table public.app_adjustments
    add column if not exists source text;

update public.app_adjustments
set source = case
    when lower(coalesce(note, '')) like '%[ui_edit]%'
      or lower(coalesce(note, '')) like 'edit->%'
      or lower(coalesce(note, '')) like 'ui_edit%'
      or lower(coalesce(note, '')) like 'ui edit%'
      or coalesce(note, '') like 'UI编辑%'
    then 'ui_edit'
    else 'manual'
end
where source is null or btrim(source) = '';

alter table public.app_adjustments
    alter column source set default 'manual',
    alter column source set not null;

create table if not exists public.app_daily_ledger (
    user_id text not null,
    date date not null,
    code text not null,
    shares_end double precision not null default 0,
    avg_cost_nav_end double precision not null default 0,
    realized_pnl_end double precision not null default 0,
    estimated_nav_close double precision,
    estimated_pnl_close double precision,
    official_nav double precision,
    official_pnl double precision,
    settle_status text not null default 'estimated_only',
    updated_at timestamptz not null default now()
);

-- Fail closed instead of silently deleting or merging potentially conflicting
-- user data. Resolve any reported duplicates using the documented preflight.
do $$
begin
    if exists (
        select 1 from public.app_users
        where user_id is null or btrim(user_id::text) = ''
           or phone is null or btrim(phone::text) = ''
           or password_hash is null or btrim(password_hash::text) = ''
    ) then
        raise exception using
            errcode = '23502',
            message = 'security migration blocked: incomplete app_users identity rows';
    end if;
    if exists (
        select 1 from public.app_watchlist
        where user_id is null or btrim(user_id::text) = ''
           or code is null or btrim(code::text) = ''
    ) or exists (
        select 1 from public.app_adjustments
        where user_id is null or btrim(user_id::text) = ''
           or id is null or btrim(id::text) = ''
           or code is null or btrim(code::text) = ''
    ) or exists (
        select 1 from public.app_daily_ledger
        where user_id is null or btrim(user_id::text) = ''
           or code is null or btrim(code::text) = ''
    ) then
        raise exception using
            errcode = '23502',
            message = 'security migration blocked: business rows without an owner/key';
    end if;
    if exists (
        select 1 from public.app_users
        group by phone
        having count(*) > 1
    ) then
        raise exception using
            errcode = '23505',
            message = 'security migration blocked: duplicate app_users.phone values';
    end if;
    if exists (
        select 1 from public.app_users
        group by user_id
        having count(*) > 1
    ) then
        raise exception using
            errcode = '23505',
            message = 'security migration blocked: duplicate app_users.user_id values';
    end if;
    if exists (
        select 1 from public.app_watchlist
        group by user_id, code
        having count(*) > 1
    ) then
        raise exception using
            errcode = '23505',
            message = 'security migration blocked: duplicate app_watchlist owner/code values';
    end if;
    if exists (
        select 1 from public.app_adjustments
        group by user_id, id
        having count(*) > 1
    ) then
        raise exception using
            errcode = '23505',
            message = 'security migration blocked: duplicate app_adjustments owner/id values';
    end if;
    if exists (
        select 1 from public.app_daily_ledger
        group by user_id, date, code
        having count(*) > 1
    ) then
        raise exception using
            errcode = '23505',
            message = 'security migration blocked: duplicate app_daily_ledger owner/date/code values';
    end if;
end
$$;

