-- Atomically replaces only the selected day's UI-generated adjustment rows,
-- replays the remaining position, and writes the minimal rows needed to reach
-- the requested end-of-day target. PostgreSQL executes one RPC call in one
-- transaction; any exception rolls the entire edit back.
create or replace function public.app_apply_position_edit(
    p_user_id text,
    p_effective_date date,
    p_code text,
    p_shares_end double precision,
    p_avg_cost_nav_end double precision,
    p_realized_pnl_end double precision default 0,
    p_note text default null
)
returns jsonb
language plpgsql
security invoker
set search_path = pg_catalog
as $$
declare
    v_row record;
    v_shares double precision := 0;
    v_avg double precision := 0;
    v_realized double precision := 0;
    v_delta double precision := 0;
    v_trade_shares double precision := 0;
    v_trade_price double precision := 0;
    v_old_amount double precision := 0;
    v_rebalance_shares double precision := 0;
    v_deleted integer := 0;
    v_inserted integer := 0;
    v_note text := nullif(btrim(p_note), '');
    v_created_at timestamptz := clock_timestamp();
begin
    if p_user_id is null or btrim(p_user_id) = '' or length(p_user_id) > 128 then
        raise exception using errcode = '22023', message = 'invalid user identifier';
    end if;
    if p_code is null or p_code !~ '^[0-9]{6}$' then
        raise exception using errcode = '22023', message = 'invalid fund code';
    end if;
    if p_effective_date is null then
        raise exception using errcode = '22023', message = 'invalid effective date';
    end if;
    if p_shares_end::text in ('NaN', 'Infinity', '-Infinity')
       or p_avg_cost_nav_end::text in ('NaN', 'Infinity', '-Infinity')
       or p_realized_pnl_end::text in ('NaN', 'Infinity', '-Infinity')
       or p_shares_end < 0
       or p_shares_end > 1e15
       or p_avg_cost_nav_end < 0
       or p_avg_cost_nav_end > 1e12
       or abs(p_realized_pnl_end) > 1e18
       or (p_shares_end > 0 and p_avg_cost_nav_end <= 0) then
        raise exception using errcode = '22023', message = 'invalid position target';
    end if;
    if v_note is not null and length(v_note) > 500 then
        raise exception using errcode = '22023', message = 'position note is too long';
    end if;

    -- Authenticated callers may only address their mapped application user.
    -- SQL editor/admin and service_role calls have no auth.uid() and are
    -- additionally protected by function/table grants.
    if (select auth.uid()) is not null
       and p_user_id is distinct from (select private.current_app_user_id()) then
        raise exception using errcode = '42501', message = 'position owner mismatch';
    end if;

    perform pg_advisory_xact_lock(
        hashtextextended(p_user_id || ':' || p_effective_date::text || ':' || p_code, 0)
    );

    delete from public.app_adjustments
    where user_id = p_user_id
      and code = p_code
      and effective_date = p_effective_date
      and (
          lower(coalesce(source, '')) = 'ui_edit'
          or (
              coalesce(source, '') = ''
              and (
                  lower(coalesce(note, '')) like '%[ui_edit]%'
                  or lower(coalesce(note, '')) like 'edit->%'
                  or lower(coalesce(note, '')) like 'ui_edit%'
                  or lower(coalesce(note, '')) like 'ui edit%'
                  or coalesce(note, '') like 'UI编辑%'
              )
          )
      );
    get diagnostics v_deleted = row_count;

    for v_row in
        select type, shares, price, cash
        from public.app_adjustments
        where user_id = p_user_id
          and code = p_code
          and effective_date <= p_effective_date
        order by effective_date asc, created_at asc nulls last, id asc
    loop
        if upper(coalesce(v_row.type, '')) = 'BUY'
           and coalesce(v_row.shares, 0) > 0
           and coalesce(v_row.price, 0) > 0 then
            v_old_amount := v_shares * v_avg;
            v_shares := v_shares + v_row.shares;
            v_avg := (v_old_amount + v_row.shares * v_row.price) / v_shares;
        elsif upper(coalesce(v_row.type, '')) = 'SELL'
              and coalesce(v_row.shares, 0) > 0
              and coalesce(v_row.price, 0) > 0 then
            v_trade_shares := least(v_row.shares, greatest(v_shares, 0));
            v_realized := v_realized + (v_row.price - v_avg) * v_trade_shares;
            v_shares := v_shares - v_trade_shares;
            if v_shares <= 1e-9 then
                v_shares := 0;
                v_avg := 0;
            end if;
        elsif upper(coalesce(v_row.type, '')) = 'CASH_ADJ' then
            v_realized := v_realized + coalesce(v_row.cash, 0);
        end if;
    end loop;

    v_delta := p_shares_end - v_shares;
    if abs(v_delta) > 1e-9 then
        v_trade_price := case
            when p_avg_cost_nav_end > 0 then p_avg_cost_nav_end
            else 1
        end;
        if v_delta > 0 then
            v_created_at := v_created_at + interval '1 microsecond';
            insert into public.app_adjustments (
                id, user_id, type, code, effective_date, shares, price,
                cash, note, source, created_at
            ) values (
                replace(gen_random_uuid()::text, '-', ''), p_user_id, 'BUY',
                p_code, p_effective_date, v_delta, v_trade_price, 0,
                coalesce(v_note, 'edit->BUY'), 'ui_edit', v_created_at
            );
            v_old_amount := v_shares * v_avg;
            v_shares := v_shares + v_delta;
            v_avg := (v_old_amount + v_delta * v_trade_price) / v_shares;
        else
            v_trade_shares := least(abs(v_delta), greatest(v_shares, 0));
            v_created_at := v_created_at + interval '1 microsecond';
            insert into public.app_adjustments (
                id, user_id, type, code, effective_date, shares, price,
                cash, note, source, created_at
            ) values (
                replace(gen_random_uuid()::text, '-', ''), p_user_id, 'SELL',
                p_code, p_effective_date, v_trade_shares, v_trade_price, 0,
                coalesce(v_note, 'edit->SELL'), 'ui_edit', v_created_at
            );
            v_realized := v_realized + (v_trade_price - v_avg) * v_trade_shares;
            v_shares := v_shares - v_trade_shares;
            if v_shares <= 1e-9 then
                v_shares := 0;
                v_avg := 0;
            end if;
        end if;
        v_inserted := v_inserted + 1;
    end if;

    if v_shares > 0 and abs(v_avg - p_avg_cost_nav_end) > 1e-9 then
        if p_avg_cost_nav_end > v_avg then
            v_rebalance_shares := v_shares;
            v_trade_price := greatest(0.000001, 2 * p_avg_cost_nav_end - v_avg);
        else
            v_trade_price := greatest(0.000001, p_avg_cost_nav_end * 0.5);
            v_rebalance_shares :=
                v_shares * (v_avg - p_avg_cost_nav_end)
                / greatest(p_avg_cost_nav_end - v_trade_price, 1e-9);
        end if;

        v_created_at := v_created_at + interval '1 microsecond';
        insert into public.app_adjustments (
            id, user_id, type, code, effective_date, shares, price,
            cash, note, source, created_at
        ) values (
            replace(gen_random_uuid()::text, '-', ''), p_user_id, 'BUY',
            p_code, p_effective_date, v_rebalance_shares, v_trade_price, 0,
            coalesce(v_note, 'edit->COST_REBALANCE_BUY'), 'ui_edit', v_created_at
        );
        v_old_amount := v_shares * v_avg;
        v_shares := v_shares + v_rebalance_shares;
        v_avg := (v_old_amount + v_rebalance_shares * v_trade_price) / v_shares;

        v_created_at := v_created_at + interval '1 microsecond';
        insert into public.app_adjustments (
            id, user_id, type, code, effective_date, shares, price,
            cash, note, source, created_at
        ) values (
            replace(gen_random_uuid()::text, '-', ''), p_user_id, 'SELL',
            p_code, p_effective_date, v_rebalance_shares, p_avg_cost_nav_end, 0,
            coalesce(v_note, 'edit->COST_REBALANCE_SELL'), 'ui_edit', v_created_at
        );
        v_realized :=
            v_realized + (p_avg_cost_nav_end - v_avg) * v_rebalance_shares;
        v_shares := v_shares - v_rebalance_shares;
        if v_shares <= 1e-9 then
            v_shares := 0;
            v_avg := 0;
        end if;
        v_inserted := v_inserted + 2;
    end if;

    v_delta := p_realized_pnl_end - v_realized;
    if abs(v_delta) > 1e-6 then
        v_created_at := v_created_at + interval '1 microsecond';
        insert into public.app_adjustments (
            id, user_id, type, code, effective_date, shares, price,
            cash, note, source, created_at
        ) values (
            replace(gen_random_uuid()::text, '-', ''), p_user_id, 'CASH_ADJ',
            p_code, p_effective_date, 0, 0, v_delta,
            coalesce(v_note, 'edit->CASH_ADJ'), 'ui_edit', v_created_at
        );
        v_inserted := v_inserted + 1;
    end if;

    return jsonb_build_object(
        'ok', true,
        'deleted', v_deleted,
        'inserted', v_inserted
    );
end
$$;

revoke all on function public.app_apply_position_edit(
    text, date, text, double precision, double precision, double precision, text
) from public, anon;
grant execute on function public.app_apply_position_edit(
    text, date, text, double precision, double precision, double precision, text
) to authenticated, service_role;

commit;
